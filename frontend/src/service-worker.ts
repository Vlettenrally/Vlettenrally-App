// Cache API requests
// Match both relative paths and the full API URL from build-time config
registerRoute(
  ({ url }) => {
    // Match relative API paths (development)
    if (url.pathname.startsWith('/api/')) return true;
    
    // Match full API URL (production)
    try {
      const apiUrl = new URL(API_BASE_URL);
      return url.hostname === apiUrl.hostname && url.pathname.startsWith(apiUrl.pathname);
    } catch {
      return false;
    }
  },
  new NetworkFirst({
    cacheName: 'api-cache',
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 3600, // 1 hour
      }),
    ],
  })
)

// Cache images
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: 'images-cache',
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
)

